/**
 * Wire format between the board UI and its BoardRoom Durable Object.
 * Types only, so the client bundle doesn't pull in validation code; the
 * server validates incoming messages with src/server/operation-schema.ts.
 */

export type OptionState = {
  id: string
  text: string
  /** Null while the decision hides its results and voting is still open. */
  votes: number | null
}

export type DecisionState = {
  id: string
  title: string
  createdById: string
  createdAt: number
  /** Voting stops at this time (ms), if set. */
  closesAt: number | null
  /** When someone closed voting by hand (ms). */
  closedAt: number | null
  hideResults: boolean
  /** Always visible, even when per-option counts are hidden. */
  totalVotes: number
  options: Array<OptionState>
}

/**
 * What someone can do on a board. Owners do everything; editors ask
 * questions; voters vote and add options; viewers only watch.
 */
export type Role = 'owner' | 'editor' | 'voter' | 'viewer'

/** Roles an invite link can grant. */
export type InviteRole = 'editor' | 'voter'

/** Board contents that are the same for every viewer. */
export type BoardState = {
  board: {
    id: string
    name: string
    ownerId: string
    createdAt: number
  }
  decisions: Array<DecisionState>
}

/** One viewer's votes: decision id → option id. */
export type VoteMap = Record<string, string>

export type BoardSnapshot = {
  state: BoardState
  myVotes: VoteMap
  /** The viewer's own role on this board. */
  role: Role
}

/**
 * Changes a client can request. Ids are generated by the client so the UI
 * can show a change before the server confirms it, and so replaying an
 * operation after a dropped connection has no extra effect.
 */
export type Operation =
  | {
      kind: 'createDecision'
      decisionId: string
      title: string
      options: Array<{ id: string; text: string }>
      closesAt: number | null
      hideResults: boolean
    }
  | { kind: 'renameDecision'; decisionId: string; title: string }
  | { kind: 'deleteDecision'; decisionId: string }
  | { kind: 'addOption'; decisionId: string; optionId: string; text: string }
  /** Sets rather than toggles the vote, so replays are harmless. */
  | { kind: 'setVote'; decisionId: string; optionId: string | null }
  /** Closes voting now, or reopens it with no deadline. */
  | { kind: 'setDecisionClosed'; decisionId: string; closed: boolean }
  /** Sets the board's name. Owner only. */
  | { kind: 'renameBoard'; name: string }

export type ClientMessage = {
  type: 'op'
  opId: string
  op: Operation
}

/** Someone looking at the board right now. One entry per person, not per tab. */
export type Person = {
  /** User id, or a per-connection id for visitors without a session. */
  key: string
  name: string
  image: string | null
  emoji: string
  color: string
  isGuest: boolean
}

export type ActivityKind =
  | 'createDecision'
  | 'renameDecision'
  | 'deleteDecision'
  | 'addOption'
  | 'setVote'
  | 'setDecisionClosed'

export type ServerMessage =
  /** Sent on connect. `viewerId` is who the server thinks this socket is. */
  | {
      type: 'snapshot'
      viewerId: string | null
      snapshot: BoardSnapshot
      /** This connection's own presence key. */
      you: string
      people: Array<Person>
    }
  /** Broadcast to everyone after a change. */
  | { type: 'state'; state: BoardState }
  /** Sent to a user's own connections when their votes change. */
  | { type: 'myVotes'; myVotes: VoteMap }
  | { type: 'ack'; opId: string }
  | { type: 'reject'; opId: string; reason: string }
  /** Broadcast when someone joins or leaves. */
  | { type: 'presence'; people: Array<Person> }
  /**
   * Who just changed what, so other viewers can see it happen. Never says
   * which option someone voted for.
   */
  | {
      type: 'activity'
      personKey: string
      decisionId: string
      kind: ActivityKind
    }
  /** The owner deleted the board. The room closes every socket after this. */
  | { type: 'deleted' }

export const BOARD_PARTY = 'board-room'

export const LIMITS = {
  boardNameLength: 100,
  decisionsPerBoard: 100,
  optionsPerDecision: 50,
  messageBytes: 32_000,
  /** Deadlines can be at most this far ahead. */
  maxDeadlineMs: 90 * 24 * 60 * 60 * 1000,
} as const

const ROLE_RANK: Record<Role, number> = {
  viewer: 0,
  voter: 1,
  editor: 2,
  owner: 3,
}

export function hasRole(role: Role, atLeast: Role) {
  return ROLE_RANK[role] >= ROLE_RANK[atLeast]
}

/** The higher of two roles; invites never demote anyone. */
export function higherRole<T extends Role>(a: T, b: T): T {
  return ROLE_RANK[a] >= ROLE_RANK[b] ? a : b
}

export function isDecisionOpen(
  decision: Pick<DecisionState, 'closesAt' | 'closedAt'>,
  now: number,
) {
  return (
    decision.closedAt === null &&
    (decision.closesAt === null || now < decision.closesAt)
  )
}
