/**
 * Wire format between the board UI and its BoardRoom Durable Object.
 * Types only, so the client bundle doesn't pull in validation code; the
 * server validates incoming messages with src/server/operation-schema.ts.
 */

export type OptionState = {
  id: string
  text: string
  votes: number
}

export type DecisionState = {
  id: string
  title: string
  createdById: string
  createdAt: number
  options: Array<OptionState>
}

/** Board contents that are the same for every viewer. */
export type BoardState = {
  board: {
    id: string
    name: string
    ownerId: string
    createdAt: number
  }
  decisions: Array<DecisionState>
}

/** One viewer's votes: decision id → option id. */
export type VoteMap = Record<string, string>

export type BoardSnapshot = {
  state: BoardState
  myVotes: VoteMap
}

/**
 * Changes a client can request. Ids are generated by the client so the UI
 * can show a change before the server confirms it, and so replaying an
 * operation after a dropped connection has no extra effect.
 */
export type Operation =
  | {
      kind: 'createDecision'
      decisionId: string
      title: string
      options: Array<{ id: string; text: string }>
    }
  | { kind: 'renameDecision'; decisionId: string; title: string }
  | { kind: 'deleteDecision'; decisionId: string }
  | { kind: 'addOption'; decisionId: string; optionId: string; text: string }
  /** Sets rather than toggles the vote, so replays are harmless. */
  | { kind: 'setVote'; decisionId: string; optionId: string | null }

export type ClientMessage = {
  type: 'op'
  opId: string
  op: Operation
}

/** Someone looking at the board right now. One entry per person, not per tab. */
export type Person = {
  /** User id, or a per-connection id for visitors without a session. */
  key: string
  name: string
  image: string | null
  emoji: string
  color: string
  isGuest: boolean
}

export type ActivityKind =
  | 'createDecision'
  | 'renameDecision'
  | 'deleteDecision'
  | 'addOption'
  | 'setVote'

export type ServerMessage =
  /** Sent on connect. `viewerId` is who the server thinks this socket is. */
  | {
      type: 'snapshot'
      viewerId: string | null
      snapshot: BoardSnapshot
      /** This connection's own presence key. */
      you: string
      people: Array<Person>
    }
  /** Broadcast to everyone after a change. */
  | { type: 'state'; state: BoardState }
  /** Sent to a user's own connections when their votes change. */
  | { type: 'myVotes'; myVotes: VoteMap }
  | { type: 'ack'; opId: string }
  | { type: 'reject'; opId: string; reason: string }
  /** Broadcast when someone joins or leaves. */
  | { type: 'presence'; people: Array<Person> }
  /**
   * Who just changed what, so other viewers can see it happen. Never says
   * which option someone voted for.
   */
  | {
      type: 'activity'
      personKey: string
      decisionId: string
      kind: ActivityKind
    }

export const BOARD_PARTY = 'board-room'

export const LIMITS = {
  decisionsPerBoard: 100,
  optionsPerDecision: 50,
  messageBytes: 32_000,
} as const
